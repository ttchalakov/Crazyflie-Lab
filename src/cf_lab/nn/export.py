"""Write quantized networks as C arrays and ``cf_nn_net_t`` objects for an STM32 app (and the host build).

Every array is ``static const`` and 4-byte aligned, so it stays in flash on the STM32 and the kernels read whole
words; an app that wants weights in RAM or CCM copies them there itself. Arrays with identical contents are written
once, so the three float formats of one network share their weights.
"""

from __future__ import annotations

import hashlib
from collections.abc import Mapping
from pathlib import Path

import numpy as np

from cf_lab.nn.quant import ACT_CODES, FORMAT_CODES, QuantNet

_C_TYPES = {
    np.dtype(np.float32): "float",
    np.dtype(np.int8): "int8_t",
    np.dtype(np.int16): "int16_t",
    np.dtype(np.int32): "int32_t",
    np.dtype(np.int64): "int64_t",
}


def c_float(value: float) -> str:
    """A float literal that reads back as exactly this float32."""
    return f"{float(np.float32(value)):.9e}f"


def _c_int(value: int, dtype: np.dtype) -> str:
    if dtype == np.int64:
        return f"INT64_C({value})" if value != -(2**63) else "INT64_MIN"
    if dtype == np.int32 and value == -(2**31):
        return "INT32_MIN"
    return str(value)


def c_array_body(values: np.ndarray, per_line: int = 16) -> str:
    flat = values.reshape(-1)
    if flat.dtype == np.float32:
        items = [c_float(v) for v in flat]
    else:
        items = [_c_int(int(v), flat.dtype) for v in flat]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "  " + ",\n  ".join(lines)


class _Arrays:
    """Emits each distinct array once and remembers its symbol."""

    def __init__(self) -> None:
        self.lines: list[str] = []
        self._symbols: dict[tuple[str, int, str], str] = {}

    def add(self, name: str, values: np.ndarray | None) -> str:
        if values is None:
            return "NULL"
        values = np.ascontiguousarray(values)
        ctype = _C_TYPES[values.dtype]
        key = (ctype, values.size, hashlib.sha1(values.tobytes()).hexdigest())
        if key in self._symbols:
            return self._symbols[key]
        self._symbols[key] = name
        self.lines.append(
            f"static const {ctype} {name}[{values.size}] __attribute__((aligned(4))) = {{\n"
            f"{c_array_body(values)}\n}};\n"
        )
        return name


def _layer_struct(net: QuantNet, name: str, arrays: _Arrays) -> str:
    entries = []
    for k, layer in enumerate(net.layers):
        w = arrays.add(f"{name}_w{k}", layer.w)
        b = arrays.add(f"{name}_b{k}", layer.b)
        dims = f".in = {layer.n_in}, .in_pad = {layer.in_pad}, .out = {layer.n_out}"
        if net.fmt.startswith("f32"):
            entries.append(f"  {{{dims}, .act = {ACT_CODES[layer.act]}, .w = {w}, .b = {b}}}")
            continue
        mult = arrays.add(f"{name}_m{k}", layer.mult)
        shift = arrays.add(f"{name}_s{k}", layer.shift)
        lut = arrays.add(f"{name}_lut{k}", layer.lut)
        offsets = f", .in_offset = {layer.in_offset}, .out_offset = {layer.out_offset}" if net.fmt == "s8" else ""
        entries.append(f"  {{{dims}{offsets}, .w = {w}, .b = {b}, .mult = {mult}, .shift = {shift}, .lut = {lut}}}")
    kind = {"s8": "s8", "s16s8": "s16s8", "s16": "s16"}.get(net.fmt, "f32")
    return (f"static const cf_nn_{kind}_layer_t {name}_layers[{len(net.layers)}] = {{\n"
            + ",\n".join(entries) + "\n};\n")


def _net_struct(net: QuantNet, name: str, arrays: _Arrays) -> str:
    in_scale = arrays.add(f"{name}_in_scale", net.in_scale)
    in_bias = arrays.add(f"{name}_in_bias", net.in_bias)
    return (
        f"const cf_nn_net_t {name} = {{\n"
        f"  .format = {FORMAT_CODES[net.fmt]}, .n_layers = {len(net.layers)}, .in = {net.n_in}, "
        f".out = {net.n_out}, .max_width = {net.max_width},\n"
        f"  .layers = {name}_layers, .in_scale = {in_scale}, .in_bias = {in_bias},\n"
        f"  .out_scale = {c_float(net.out_scale)}, .out_zero = {net.out_zero},\n"
        f"}};\n"
    )


def write_c(nets: Mapping[str, QuantNet], c_path: Path, h_path: Path, *, extra_c: str = "",
            extra_h: str = "") -> None:
    """Write ``nets`` (C symbol -> network) to ``c_path`` and their declarations to ``h_path``."""
    c_path, h_path = Path(c_path), Path(h_path)
    guard = "".join(ch if ch.isalnum() else "_" for ch in h_path.name.upper())
    arrays = _Arrays()
    bodies = []
    for name, net in nets.items():
        layers = _layer_struct(net, name, arrays)
        bodies.append(layers + _net_struct(net, name, arrays))
    header = (
        "// Generated by cf_lab.nn.export; do not edit.\n"
        f"#ifndef {guard}\n#define {guard}\n\n#include \"cf_lab/nn.h\"\n\n"
        + "".join(f"extern const cf_nn_net_t {name};\n" for name in nets)
        + (f"\n{extra_h}" if extra_h else "") + "\n#endif\n"
    )
    source = (
        "// Generated by cf_lab.nn.export; do not edit.\n"
        f"#include <stddef.h>\n#include <stdint.h>\n\n#include \"{h_path.name}\"\n\n"
        + "\n".join(arrays.lines) + "\n" + "\n".join(bodies) + (f"\n{extra_c}" if extra_c else "")
    )
    h_path.parent.mkdir(parents=True, exist_ok=True)
    c_path.parent.mkdir(parents=True, exist_ok=True)
    h_path.write_text(header)
    c_path.write_text(source)
