"""The scheduler_bench networks: generated DORY applications plus sched_net.h.

Each network is synthesised with random integer weights in NEMO's ONNX dialect,
code-generated by the real DORY in its container, and described to lib/gap8/sched
by a generated sched_net.h. The weights mean nothing; what is measured is how the
schedulers fit a network of that shape beside the camera and the video stream.

Two families, both built with nn_bench's generator (examples/nn_bench/host/graph.py):
  mlp       a state policy: a vector in
  convpool  an image policy: the camera frame in, at the camera's own size, so one
            entry builds a network per frame size. Its units are c<channels>[s2][mp]:
            a 3x3 convolution (s2: stride 2) and (mp) a 2x2 max pool after it; then
            a global average pool and a 4-output layer.

DORY sizes a 3-level (l3) arena from the L2 it is told it may use ("code reserved
space" is what it must leave alone). Its default leaves the camera, the JPEG
encoder and the CPX send queue no room, so l3 networks are generated with the
budget the bench gives them (arena_kb). A 2-level (l2) arena holds activations
only and is sized here, exactly.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parents[1]
ROOT = BENCH_DIR.parents[1]
sys.path.insert(0, str(ROOT / "examples" / "nn_bench" / "host"))

import graph as graphs  # noqa: E402
import networks  # noqa: E402
import point as points  # noqa: E402
import reference  # noqa: E402
from cf_lab.aideck.dory_pipeline import rightsize_dory_hyperram  # noqa: E402

L2_BYTES = 512 * 1024
# l2 keeps weights and activations in L2; its budget only has to let DORY's
# tiler accept the network. What really fits is found on the deck.
TWO_LEVEL_BUDGET_KB = 448
# Above the arena DORY's allocator needs: its fit test is strict.
ARENA_SLACK = 64


@dataclass(frozen=True)
class NetworkSpec:
    name: str
    family: str                     # "mlp" or "convpool"
    memory: str                     # l2 or l3
    arena_kb: int = 64              # l3: the L2 DORY may use for its arena
    dims: tuple[int, ...] = ()      # mlp: layer widths
    units: tuple[str, ...] = ()     # convpool: see the module docstring
    image: tuple[int, int] = (0, 0)  # convpool: width, height (from the camera)

    @property
    def dir_name(self) -> str:
        """The name, with a convpool network's input after the family."""
        if self.family != "convpool":
            return self.name
        return f"{self.family}-{self.image[0]}x{self.image[1]}c1{self.name[len(self.family):]}"


def parse_spec(name: str, entry: dict, image: tuple[int, int] = (0, 0)) -> NetworkSpec:
    family = entry["family"]
    if family not in ("mlp", "convpool"):
        raise SystemExit(f"{name}: unknown network family {family!r}")
    return NetworkSpec(name=name, family=family, memory=entry["memory"],
                       arena_kb=int(entry.get("arena_kb", 64)),
                       dims=tuple(entry.get("dims", ())), units=tuple(entry.get("units", ())),
                       image=image if family == "convpool" else (0, 0))


def build(spec: NetworkSpec) -> graphs.Graph:
    if spec.family == "mlp":
        return networks.mlp(list(spec.dims))
    width, height = spec.image
    graph = graphs.Graph((1, height, width))
    for index, unit in enumerate(spec.units):
        if not (m := re.fullmatch(r"c(\d+)(s2)?(mp)?", unit)):
            raise SystemExit(f"{spec.name}: bad unit {unit!r} (c<channels>[s2][mp])")
        graph.conv(int(m.group(1)), 3, 2 if m.group(2) else 1, f"unit{index}_conv")
        if m.group(3):
            graph.maxpool2(f"unit{index}_pool")
    graph.global_average()
    graph.fc(4, requant=False, label="out")
    return graph


def prepare(spec: NetworkSpec, out_root: Path, force: bool = False) -> Path:
    """Generate the DORY app and sched_net.h; return the network directory."""
    out = out_root.resolve() / spec.dir_name
    if force or not (out / "gap8_app" / "src" / "network.c").exists():
        generate(spec, out)
    # Always: it is cheap, and it tracks this file rather than the app's age.
    (out / "gen").mkdir(parents=True, exist_ok=True)
    emit_sched_net(spec, out / "gap8_app", out / "gen" / "sched_net.h")
    return out


def generate(spec: NetworkSpec, out: Path) -> None:
    """Synthesise the model, code-generate it through DORY and check DORY's app."""
    budget_kb = spec.arena_kb if spec.memory == "l3" else TWO_LEVEL_BUDGET_KB
    graph = build(spec)
    graphs.write(graph, out, spec.name, code_reserved_space=L2_BYTES - budget_kb * 1024)
    app = points.codegen(out, spec.memory)
    rightsize_dory_hyperram(app_dir=app, largest_activation=points.largest_activation(graph))
    # The deck then checks DORY's kernels against DORY's goldens (SCHED_VERIFY).
    if failures := reference.check(graph, app):
        raise SystemExit(f"{spec.name}: DORY's app is not the network written: {failures}")


def _ints(text: str, name: str) -> list[int]:
    m = re.search(rf"{name}\[[^\]]*\](?:\[[^\]]*\])? = \{{(.*?)\}};", text, re.S)
    if not m:
        raise SystemExit(f"no {name} in the generated network.h")
    return [int(x) for x in re.findall(r"-?\d+", m.group(1))]


def two_level_arena(in_sizes: list[int], out_sizes: list[int]) -> int:
    """What DORY's 2-level run loop takes from its directional allocator.

    The first layer reads the caller's input in place; every later layer holds
    its input (the previous output) and its output at once, at opposite ends.
    Branches would hold a bypass too; these chains have none.
    """
    need = max([out_sizes[0]] + [i + o for i, o in zip(in_sizes[1:], out_sizes[1:])])
    return (need + ARENA_SLACK + 15) & ~15


def emit_sched_net(spec: NetworkSpec, app_dir: Path, path: Path) -> None:
    """Describe a generated DORY app to lib/gap8/sched."""
    src = (app_dir / "src" / "network.c").read_text(encoding="utf-8")
    hdr = (app_dir / "inc" / "network.h").read_text(encoding="utf-8")
    main_c = (app_dir / "src" / "main.c").read_text(encoding="utf-8")
    three_level = "network_initialize" in src

    in_sizes = _ints(hdr, "activations_size")
    out_sizes = _ints(hdr, "activations_out_size")
    golden = _ints(hdr, "activations_out_checksum")
    input_bytes, output_bytes, golden_sum = in_sizes[0], out_sizes[-1], golden[-1]
    if spec.family == "convpool" and input_bytes != spec.image[0] * spec.image[1]:
        raise SystemExit(f"{spec.name}: DORY's input is {input_bytes} B, not one "
                         f"{spec.image[0]}x{spec.image[1]} frame")
    m = re.search(r"cluster_task\.stack_size = (\d+)", src)
    stack = int(m.group(1)) if m else 3500
    m = re.search(r"cluster_task\.slave_stack_size = (\d+)", src)
    slave = int(m.group(1)) if m else 3400
    if three_level:
        # The 3-level arena also holds staged weight tiles, so it is DORY's
        # number, never ours (see examples/nn_bench/host/point.py).
        arena = int(re.search(r"pi_l2_malloc\((\d+)\)", main_c).group(1))
    else:
        arena = two_level_arena(in_sizes, out_sizes)

    state = spec.family == "mlp"
    L = [
        "// GENERATED by examples/scheduler_bench/host/sched_net.py -- do not edit.",
        "#ifndef SCHED_NET_H",
        "#define SCHED_NET_H",
        "#include <string.h>",
        '#include "sched.h"',
        '#include "network.h"',
    ]
    if three_level:
        L.append('#include "mem.h"')
    elif state:
        L.append('#include "input.h"')
    L += ["", f"#define SCHED_NET_STATE_BYTES {input_bytes if state else 0}", ""]
    if state and three_level:
        L += [
            "static void *schedNetGolden;",
            "",
            "// Mounts the flash, loads the weights into HyperRAM, and keeps DORY's",
            "// golden input there for the verification runs.",
            "static void schedNetInitialize(void) {",
            "  mem_init();",
            "  network_initialize();",
            f"  schedNetGolden = ram_malloc({input_bytes});",
            '  load_file_to_ram(schedNetGolden, "inputs.hex");',
            "}",
            "",
            "static void schedNetStageGolden(void *dst) {",
            f"  ram_read(dst, schedNetGolden, {input_bytes});",
            "}",
            "",
        ]
    elif state:
        L += [
            "static void schedNetStageGolden(void *dst) {",
            f"  memcpy(dst, L2_input_h, {input_bytes});",
            "}",
            "",
        ]
    else:
        if three_level:
            L += [
                "// Mounts the flash and loads the weights into HyperRAM.",
                "static void schedNetInitialize(void) {",
                "  mem_init();",
                "  network_initialize();",
                "}",
                "",
            ]
        L += [
            "// The golden input: nn_bench's graph.xorshift_bytes().",
            "static void schedNetStageGolden(void *dst) {",
            "  uint8_t *bytes = (uint8_t *)dst;",
            f"  uint32_t x = {graphs.XORSHIFT_SEED}u;",
            f"  for (uint32_t i = 0; i < {input_bytes}u; i++) {{",
            "    x ^= x << 13;",
            "    x ^= x >> 17;",
            "    x ^= x << 5;",
            "    bytes[i] = (uint8_t)x;",
            "  }",
            "}",
            "",
        ]
    L += [
        "static const sched_network_t SCHED_NETWORK = {",
        f'    .name = "{spec.name}",',
        "    .input = SCHED_INPUT_STATE," if state else "    .input = SCHED_INPUT_IMAGE,",
        f"    .image_width = {spec.image[0]},",
        f"    .image_height = {spec.image[1]},",
        f"    .input_bytes = {input_bytes},",
        f"    .output_bytes = {output_bytes},",
        f"    .arena_bytes = {arena},",
        f"    .three_level = {1 if three_level else 0},",
        "    .initial_dir = 1,",
        "    .initialize = schedNetInitialize," if three_level else "    .initialize = NULL,",
        "    .cluster_entry = network_run_cluster,",
        f"    .cluster_stack = {stack},",
        f"    .cluster_slave_stack = {slave},",
        "    .stage_golden = schedNetStageGolden,",
        f"    .golden_output_sum = {golden_sum}u,",
        "};",
        "",
        "#endif  // SCHED_NET_H",
    ]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
