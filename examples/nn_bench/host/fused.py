"""The fused runner: a whole network in one cluster team (gap8/fused/), on a point's tensors.

DORY runs a network a layer at a time, every layer's output going out to L2 and
back. The fused executors keep the activations in L1 for the whole inference and
fuse what a layer-at-a-time schedule cannot: a 2x2 max pool into the convolution
before it, a depthwise convolution into the pointwise after it. Each runs one
shape of network:

  mlp       fully connected layers. Weights in L2; on l3 DORY's own weight files in
            HyperRAM, streamed through L2 into L1.
  convpool  3x3 convolutions, each optionally followed by a 2x2 max pool  } then a global average
  dwpw      units of a 3x3 depthwise, a 1x1 pointwise and a 2x2 max pool } and an output layer

executor() says which runs a network; emit() writes nn_bench_fused.h: the layer table,
the tensors in the executor's layout, and the graph layer each output is. A layer
an executor never stores (a convolution before its fused pool) is reported
skipped; every other layer is checked as DORY's are.
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np

from graph import SHIFT, Graph

CORES = 8
L1_BUDGET = 65536 - (4096 + 7 * 2048) - 1024  # the cluster's L1, less the task stacks it also holds


def executor(graph: Graph, memory: str) -> str | None:
    ops = "".join({"conv": "c", "dw": "d", "fc": "f", "pool": "p", "gap": "g", "add": "a"}[l.op]
                  for l in graph.layers)
    if re.fullmatch("f+", ops):
        return "mlp"
    if memory != "l2":  # the convpool and dwpw executors read their weights from L2
        return None
    convs = [l for l in graph.layers if l.op in ("conv", "dw")]
    if not all(l.values.shape[0] % 4 == 0 for l in convs):  # the 4-channel matmul
        return None
    if re.fullmatch("(cp?)+gf", ops) and all(l.weights.shape[-1] == 3 for l in convs) \
            and l1_bytes(convpool_tables(graph)) <= L1_BUDGET:
        return "convpool"
    if re.fullmatch("(dcp)+gf", ops) and all(l.weights.shape[-1] == 1 for l in convs if l.op == "conv") \
            and l1_bytes(dwpw_tables(graph)) <= L1_BUDGET:
        return "dwpw"
    return None


def array(ctype: str, name: str, values) -> str:
    flat = np.asarray(values).reshape(-1)
    rows = [", ".join(str(int(v)) for v in flat[i:i + 24]) for i in range(0, max(flat.size, 1), 24)]
    return f"static const {ctype} {name}[{max(flat.size, 1)}] __attribute__((aligned(4))) = {{\n  " \
        + ",\n  ".join(rows) + "};"


def emit(graph: Graph, name: str, memory: str, app: Path, path: Path) -> None:
    lines = {"mlp": mlp_header, "convpool": convpool_header, "dwpw": dwpw_header}[name](graph, memory, app)
    path.write_text("\n".join([
        "// GENERATED by examples/nn_bench/host/fused.py -- do not edit.",
        "#ifndef NN_BENCH_FUSED_H", "#define NN_BENCH_FUSED_H", "#include <stdint.h>",
        f"#define FUSED_SHIFT {SHIFT}", f"#define NNBENCH_INPUT_LEN {graph.input.size}",
        *lines, "#endif", ""]))


# -- mlp -----------------------------------------------------------------------

def mlp_header(graph: Graph, memory: str, app: Path) -> list[str]:
    layers = graph.layers
    dims_in = [l.weights.shape[1] for l in layers]
    dims_out = [l.weights.shape[0] for l in layers]
    width = max(dims_in + dims_out + [4 * dims_out[-1]])
    lines = [f"#define FUSED_LAYERS {len(layers)}",
             f"#define FUSED_WIDTH {(width + 3) & ~3}",
             f"#define FUSED_L3 {int(memory == 'l3')}",
             "#define NNBENCH_HAS_L3 FUSED_L3",
             "#define NNBENCH_CL_MASTER_STACK 4096", "#define NNBENCH_CL_SLAVE_STACK 2048",
             array("uint16_t", "fusedIn", dims_in), array("uint16_t", "fusedOut", dims_out),
             array("int32_t", "fusedMult", [0 if l.int32 else l.multiplier for l in layers]),
             array("uint32_t", "fusedBiasOffset", np.cumsum([0] + dims_out[:-1])),
             array("int32_t", "fusedBias", np.concatenate([l.bias for l in layers]))]
    if memory == "l3":
        # DORY's weight files hold each layer's [out][in] weights, then its biases.
        files = re.findall(r'"([^"]+)"', re.search(r"L3_weights_files\[\] = \{(.*?)\};",
                                                   (app / "inc" / "network.h").read_text(), re.S).group(1))
        lines.append("static const char *const fusedFiles[] = {" + ", ".join(f'"{f}"' for f in files) + "};")
        lines.append(array("uint32_t", "fusedFileBytes", [(app / "hex" / f).stat().st_size for f in files]))
    else:
        lines.append(array("uint32_t", "fusedWeightOffset", np.cumsum([0] + [l.weights.size for l in layers[:-1]])))
        lines.append(array("int8_t", "fusedWeights", np.concatenate([l.weights.reshape(-1) for l in layers])))
    return lines


# -- the tail convpool and dwpw share ------------------------------------------

def tail(graph: Graph) -> list[str]:
    gap, fc = graph.layers[-2], graph.layers[-1]
    return [f"#define FUSED_GAP_LAYER {len(graph.layers) - 2}", f"#define FUSED_FC_LAYER {len(graph.layers) - 1}",
            f"#define FUSED_CLASSES {fc.weights.shape[0]}", f"#define FUSED_FC_IN {fc.weights.shape[1]}",
            array("int32_t", "fusedFcBias", fc.bias)]


def l1_bytes(tables: dict) -> int:
    return sum(tables["l1"].values())


# -- convpool -----------------------------------------------------------------

def convpool_tables(graph: Graph) -> dict:
    """The stages (a convolution and the pool fused into it), and the L1 they need."""
    stages, weights, mults = [], [], []
    shape, channel, offset = graph.input.shape, 0, 0
    act = [0, 0]
    layers = graph.layers
    for i, layer in enumerate(layers):
        if layer.op != "conv":
            continue
        pooled = i + 1 < len(layers) and layers[i + 1].op == "pool"
        out = layer.values.shape
        stride = 1 if out[1] == shape[1] else 2
        buffer = (len(stages) & 1) ^ 1
        stored = layers[i + 1].values if pooled else layer.values
        act[buffer] = max(act[buffer], stored.size)
        stages.append([shape[1], shape[2], shape[0], out[1], out[2], out[0], stride, int(pooled),
                       offset, channel, buffer, i + 1 if pooled else i])
        weights.append(layer.weights.transpose(0, 2, 3, 1).reshape(-1))  # [oc][ky][kx][ic]
        mults += [layer.multiplier] * out[0]
        offset += layer.weights.size
        channel += out[0]
        shape = stored.shape
    fc = layers[-1].weights
    max_c = max(s[5] for s in stages)
    max_cols = 9 * max(s[2] for s in stages)
    l1 = {"act": act[0] + act[1] + 8, "weights": offset + fc.size, "epilogue": channel * 12,
          "im2col": 2 * CORES * max_cols, "pool": 4 * CORES * max_c * 4, "tail": max_c + 4 * fc.shape[0]}
    return {"stages": stages, "weights": weights, "mults": mults, "act": act, "max_c": max_c,
            "max_cols": max_cols, "channels": channel, "fc": fc, "l1": l1}


def convpool_header(graph: Graph, memory: str, app: Path) -> list[str]:
    t = convpool_tables(graph)
    first = t["stages"][0]
    # Stage 0 reads the frame from L2 in bands of rows into act[0], which is idle
    # until stage 1 writes it: a stride-2 pooled row needs 4 more input rows.
    band = (t["act"][0] // first[1] - 1) // 4 if first[2] == 1 and first[6] == 2 and first[7] else 0
    return [f"#define FUSED_STAGES {len(t['stages'])}", f"#define FUSED_MAX_CHANNELS {t['max_c']}",
            f"#define FUSED_MAX_COLUMNS {t['max_cols']}", f"#define FUSED_CHANNELS {t['channels']}",
            f"#define FUSED_ACT0_BYTES {t['act'][0]}", f"#define FUSED_ACT1_BYTES {t['act'][1]}",
            f"#define FUSED_BAND_ROWS {band}", f"#define FUSED_WEIGHT_BYTES {t['l1']['weights']}",
            "#define NNBENCH_HAS_L3 0", "#define NNBENCH_CL_MASTER_STACK 4096", "#define NNBENCH_CL_SLAVE_STACK 2048",
            "// in_h, in_w, in_c, out_h, out_w, out_c, stride, pool, weight_offset, channel_offset, buffer, layer",
            "static const uint32_t fusedStage[][12] = {"
            + ", ".join("{" + ", ".join(str(v) for v in s) + "}" for s in t["stages"]) + "};",
            array("int8_t", "fusedWeights", np.concatenate(t["weights"] + [t["fc"].reshape(-1)])),
            array("int32_t", "fusedMult", t["mults"]), *tail(graph)]


# -- dwpw ---------------------------------------------------------------------

def dwpw_tables(graph: Graph) -> dict:
    blocks, dw_w, pw_w, dw_m, pw_m = [], [], [], [], []
    layers = graph.layers
    shape, dw_off, pw_off, mid, outc = graph.input.shape, 0, 0, 0, 0
    act = [graph.input.size, 0]
    for i in range(0, len(layers) - 2, 3):
        dw, pw, pool = layers[i:i + 3]
        c, h, w = shape
        buffer = (len(blocks) & 1) ^ 1
        act[buffer] = max(act[buffer], pool.values.size)
        blocks.append([h, w, c, pw.values.shape[0], dw_off, pw_off, mid, outc, buffer, i + 2])
        dw_w.append(dw.weights[:, 0].reshape(c, 9).T.reshape(-1))  # tap-major: tap * C + c
        pw_w.append(pw.weights.reshape(pw.weights.shape[0], -1).reshape(-1))
        dw_m += [dw.multiplier] * c
        pw_m += [pw.multiplier] * pw.values.shape[0]
        dw_off, pw_off, mid, outc = dw_off + 9 * c, pw_off + pw.weights.size, mid + c, outc + pw.values.shape[0]
        shape = pool.values.shape
    fc = layers[-1].weights
    max_mid, max_out = max(b[2] for b in blocks), max(b[3] for b in blocks)
    l1 = {"act": act[0] + act[1] + 8, "weights": dw_off + pw_off + fc.size, "epilogue": (mid + outc) * 12,
          "scratch": 4 * CORES * (max_mid + 32 * 4), "tail": max_out + 4 * fc.shape[0]}
    return {"blocks": blocks, "dw": dw_w, "pw": pw_w, "dw_m": dw_m, "pw_m": pw_m, "act": act,
            "max_mid": max_mid, "max_out": max_out, "mid": mid, "out": outc, "dw_bytes": dw_off,
            "fc": fc, "l1": l1}


def dwpw_header(graph: Graph, memory: str, app: Path) -> list[str]:
    t = dwpw_tables(graph)
    return [f"#define FUSED_BLOCKS {len(t['blocks'])}", f"#define FUSED_MAX_MID {t['max_mid']}",
            f"#define FUSED_MAX_OUT {t['max_out']}", f"#define FUSED_MID_CHANNELS {t['mid']}",
            f"#define FUSED_OUT_CHANNELS {t['out']}", f"#define FUSED_ACT0_BYTES {t['act'][0]}",
            f"#define FUSED_ACT1_BYTES {t['act'][1]}", f"#define FUSED_DW_BYTES {t['dw_bytes']}",
            f"#define FUSED_WEIGHT_BYTES {t['l1']['weights']}",
            "#define NNBENCH_HAS_L3 0", "#define NNBENCH_CL_MASTER_STACK 2048", "#define NNBENCH_CL_SLAVE_STACK 1024",
            "// in_h, in_w, in_c, out_c, dw_offset, pw_offset, mid_offset, out_offset, buffer, layer",
            "static const uint32_t fusedBlock[][10] = {"
            + ", ".join("{" + ", ".join(str(v) for v in b) + "}" for b in t["blocks"]) + "};",
            array("int8_t", "fusedWeights", np.concatenate(t["dw"] + t["pw"] + [t["fc"].reshape(-1)])),
            array("int32_t", "fusedDwMult", t["dw_m"]), array("int32_t", "fusedPwMult", t["pw_m"]),
            *tail(graph)]
