#!/usr/bin/env python3
"""One network point: generate it, code-generate it with DORY, check it on the host,
and run it in GVSOC.

  python examples/nn_bench/host/point.py mlp-12to256to256to4 --memory l2 --gvsoc
  python examples/nn_bench/host/point.py mobilenetv1-160x120c1-a025-c8to256-out1000 --memory l3 \
      --gvsoc --runner pulp_nn lib_kernels

A point is a network (networks.py) built for one of DORY's memory models: l2
links the weights into L2; l3 keeps them in flash, loads them into HyperRAM at
boot and stages each layer's into L2 as it runs. Its directory (--out, default
artifacts/points/<network>-<memory>) holds the graph (graph.json, nemo/, dory/),
DORY's app (gap8_app/), the headers nn_bench.c builds against (gen/), host.json,
and per runner the GVSOC log and verdict (gvsoc/<runner>.log, .json). A runner
is how the network is executed: DORY with PULP-NN's kernels (pulp_nn) or with
lib/gap8/kernels (lib_kernels), or a fused executor (fused, for the networks
fused.py says one runs).
"""
from __future__ import annotations

import argparse
import fcntl
import json
import os
import re
import shutil
import statistics
import subprocess
import sys
from pathlib import Path

HOST_DIR = Path(__file__).resolve().parent
BENCH_DIR = HOST_DIR.parent
REPO = BENCH_DIR.parents[1]
sys.path.insert(0, str(HOST_DIR))

import fused  # noqa: E402
import graph as graphs  # noqa: E402
import networks  # noqa: E402
import reference  # noqa: E402
from cf_lab.aideck.dory_pipeline import rightsize_dory_hyperram  # noqa: E402

MEMORY = {"l2": "PULP.GAP8_L2", "l3": "PULP.GAP8"}  # DORY's hardware target for each
# L2 DORY leaves to the app (of its 512,000): on the deck the app's code and data
# take ~125 KB, and the readfs mount, the CPX queues and the task stacks more at
# run time. DORY's default (132,000) leaves the arena unallocatable there.
CODE_RESERVED = 180000
RUNNERS = ("pulp_nn", "lib_kernels", "fused")
NEMO_IMAGE = os.environ.get("CF_LAB_NEMO_IMAGE", "cf-lab/nemo:latest")
GAP8_IMAGE = os.environ.get("AIDECK_IMAGE", "cf-lab/aideck-gap8:latest")
# DORY writes its intermediate files under external/dory/logs, so codegens take turns.
CODEGEN_LOCK = REPO / "external" / ".dory_codegen.lock"


class PointError(RuntimeError):
    pass


def rel(path: Path, mount: str) -> str:
    return f"{mount}/{path.resolve().relative_to(REPO)}"


def codegen(out: Path, memory: str) -> Path:
    """DORY in its container: <out>/dory/config.json -> <out>/gap8_app."""
    app = out / "gap8_app"
    shutil.rmtree(app, ignore_errors=True)
    command = ["docker", "run", "--rm", "--platform", "linux/amd64", "--user", f"{os.getuid()}:{os.getgid()}",
               "-e", "HOME=/tmp", "-e", "PYTHONUNBUFFERED=1", "-v", f"{REPO}:/repo", "-w", "/repo/external/dory", NEMO_IMAGE,
               "python", "network_generate.py", "NEMO", MEMORY[memory], rel(out / "dory" / "config.json", "/repo"),
               "--app_dir", rel(app, "/repo"), "--verbose_level", "None", "--optional", "8bit"]
    with CODEGEN_LOCK.open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        proc = subprocess.run(command, capture_output=True, text=True)
    (out / "dory" / "codegen.log").write_text(proc.stdout + proc.stderr)
    # DORY exits 0 when it gives up on a layer, so the app is the verdict.
    if proc.returncode or not (app / "src" / "network.c").is_file():
        reason = [line for line in (proc.stdout + proc.stderr).splitlines() if line.strip()][-3:]
        raise PointError("DORY codegen failed: " + " / ".join(reason))
    return app


def largest_activation(graph: graphs.Graph) -> int:
    return max([graph.input.size] + [len(layer.device_bytes()) for layer in graph.layers])


def emit_net(app: Path, graph: graphs.Graph, path: Path) -> int:
    """nn_bench_net.h: which memory model DORY built, and its L2 arena. Returns the arena."""
    src = (app / "src" / "network.c").read_text()
    three_level = "network_initialize" in src
    budget = int(re.search(r"pi_l2_malloc\((\d+)\)", (app / "src" / "main.c").read_text()).group(1))
    # The 3-level arena also holds staged weight tiles: DORY's number, never ours.
    # The 2-level one holds activations only, and DORY's number would leave the
    # weights, which live beside it in L2, no room.
    largest = largest_activation(graph)
    arena = budget if three_level else min(budget, (4 * largest + 4096 + 15) & ~15)
    stack = lambda key, default: int(m.group(1)) if (m := re.search(rf"cluster_task\.{key} = (\d+)", src)) else default  # noqa: E731
    path.write_text("\n".join([
        "// GENERATED by examples/nn_bench/host/point.py -- do not edit.",
        "#ifndef NN_BENCH_NET_H",
        "#define NN_BENCH_NET_H",
        '#include "network.h"',
        *([] if three_level else ['#include "input.h"']),
        f"#define NNBENCH_HAS_L3 {int(three_level)}",
        f"#define NNBENCH_L2_ARENA {arena}",
        f"#define NNBENCH_OUTPUT_BYTES {len(graph.layers[-1].device_bytes())}",
        f"#define NNBENCH_CL_MASTER_STACK {stack('stack_size', 3500)}",
        f"#define NNBENCH_CL_SLAVE_STACK {stack('slave_stack_size', 3400)}",
        "#endif", ""]))
    return arena


def prepare(network: str, memory: str, out: Path) -> dict:
    """Generate, code-generate and check the point; host.json says how it went."""
    out.mkdir(parents=True, exist_ok=True)
    graph = networks.build(network)
    report = {"network": network, "memory": memory, "layers": len(graph.layers),
              "macs": sum(layer.macs for layer in graph.layers),
              "weight_bytes": sum(layer.weight_bytes for layer in graph.layers)}
    try:
        graphs.write(graph, out, network, code_reserved_space=CODE_RESERVED)
        app = codegen(out, memory)
        plan = rightsize_dory_hyperram(app_dir=app, largest_activation=largest_activation(graph))
        report["hyperram_bytes"] = plan.total_bytes
        report["failures"] = reference.check(graph, app)
        (out / "gen").mkdir(exist_ok=True)
        reference.emit_golden(graph, out / "gen" / "nn_bench_golden.h")
        report["l2_arena"] = emit_net(app, graph, out / "gen" / "nn_bench_net.h")
        report["fused"] = fused.executor(graph, memory)
        if report["fused"]:
            fused.emit(graph, report["fused"], memory, app, out / "gen" / "nn_bench_fused.h")
    except (PointError, reference.ReferenceError) as exc:
        report["failures"] = [str(exc)]
    (out / "host.json").write_text(json.dumps(report, indent=1) + "\n")
    return report


def make_vars(out: Path, runner: str, mount: str = "") -> str:
    path = (lambda p: rel(p, mount)) if mount else str
    executor = f" NNBENCH_FUSED={json.loads((out / 'host.json').read_text())['fused']}" if runner == "fused" else ""
    return f"NNBENCH_RUNNER={runner} NNBENCH_NET_DIR={path(out / 'gap8_app')} NNBENCH_GEN_DIR={path(out / 'gen')}{executor}"


def simulate(out: Path, runner: str, runs: int, timeout_s: int) -> str:
    """Build and run the point in GVSOC; return the output up to #DONE.

    GVSOC reboots the chip when the app exits instead of stopping, so the
    container is killed at #DONE. stdbuf matters: block-buffered output stalls
    part way and never reaches it."""
    variables = (f"platform=gvsoc io=host NNBENCH_RUNS={runs} {make_vars(out, runner, '/module')} "
                 f"BUILDDIR={rel(out / 'build' / runner, '/module')}")
    inner = (f"source /gap_sdk/configs/ai_deck.sh >/dev/null && make clean {variables} >/dev/null && "
             f"make -j4 all {variables} && timeout {timeout_s} stdbuf -oL -eL make run {variables}")
    container = f"nnbench_{os.getpid()}_{out.name}_{runner}"
    command = ["docker", "run", "--rm", "--name", container, "--platform", "linux/amd64",
               "--user", f"{os.getuid()}:{os.getgid()}", "-e", "HOME=/tmp", "-v", f"{REPO}:/module", "-w", "/module/examples/nn_bench/gap8", GAP8_IMAGE, "/bin/bash", "-lc", inner]
    lines = []
    proc = subprocess.Popen(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    try:
        for line in proc.stdout:
            lines.append(line)
            if line.startswith("#DONE"):
                break
    finally:
        subprocess.run(["docker", "rm", "-f", container], capture_output=True)
        proc.stdout.close()
        proc.wait()
    return "".join(lines)


def parse(text: str) -> dict:
    """The NN| lines: each layer of each run, each run's time, the header words."""
    text = text.replace("CPX: GAP8: ", "")  # the STM32 prefixes CPX console packets, mid-line too
    layers, runs, info = {}, {}, {}
    for body in dict.fromkeys(m.strip() for m in re.findall(r"NN\| (.*)", text)):  # the deck replays
        if m := re.fullmatch(r"r=(\d+) L(\d+) ok=(\d) us=(\d+)", body):
            layers[int(m.group(1)), int(m.group(2))] = (m.group(3) == "1", int(m.group(4)))
        elif m := re.fullmatch(r"r=(\d+) L(\d+) skip", body):  # a layer a fused executor never stores
            layers[int(m.group(1)), int(m.group(2))] = (None, None)
        elif m := re.fullmatch(r"r=(\d+) us=(\d+)", body):
            runs[int(m.group(1))] = int(m.group(2))
        elif body.startswith(("FATAL", "DONE")):
            info[body.split()[0].lower()] = body
        else:
            info.update(word.split("=", 1) for word in body.split() if "=" in word)
    return {"layers": layers, "runs": runs, "info": info}


def judge(parsed: dict, n_layers: int, runs: int) -> dict:
    """pass when every run reported every layer exact (or skipped), the output layer exact."""
    done = sorted(parsed["runs"])
    bad = sorted({layer for (run, layer), (ok, _) in parsed["layers"].items() if ok is False})
    timed = [parsed["runs"][r] for r in done[1:]] or [parsed["runs"][r] for r in done]  # run 0 also loads caches
    times = [[us for (_, i), (_, us) in parsed["layers"].items() if i == layer and us is not None]
             for layer in range(n_layers)]
    layer_us = [statistics.median(t) if t else None for t in times]
    if not parsed["runs"] and not parsed["info"]:
        result, detail = "fail", "no report (see the log)"
    elif "fatal" in parsed["info"]:
        result, detail = "fail", parsed["info"]["fatal"]
    elif bad:
        result, detail = "fail", f"layers {bad[:6]} wrong"
    elif len(done) < runs:
        result, detail = "fail", f"{len(done)} of {runs} runs reported"
    elif missing := [f"r={r} L{i}" for r in done for i in range(n_layers) if (r, i) not in parsed["layers"]]:
        result, detail = "fail", f"lines lost: {', '.join(missing[:4])}"
    elif any(parsed["layers"][r, n_layers - 1][0] is None for r in done):
        result, detail = "fail", "the output layer was not checked"
    else:
        result, detail = "pass", f"{runs} runs exact"
    return {"result": result, "detail": detail, "median_us": statistics.median(timed) if timed else None,
            "layer_us": layer_us}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("network", help="a network name (networks.py)")
    parser.add_argument("--memory", choices=MEMORY, default="l2")
    parser.add_argument("--out", type=Path, help="the point directory")
    parser.add_argument("--prepared", action="store_true", help="skip generation and codegen")
    parser.add_argument("--gvsoc", action="store_true", help="run it in GVSOC")
    parser.add_argument("--runner", nargs="+", choices=RUNNERS, default=["pulp_nn"])
    parser.add_argument("--runs", type=int, default=4)
    parser.add_argument("--timeout", type=int, default=1800, help="seconds per GVSOC run")
    args = parser.parse_args(argv)
    out = (args.out or BENCH_DIR / "artifacts" / "points" / f"{args.network}-{args.memory}").resolve()

    host = json.loads((out / "host.json").read_text()) if args.prepared else prepare(args.network, args.memory, out)
    if "fused" in args.runner and not host.get("fused"):
        args.runner.remove("fused")
        print(f"  no fused executor runs {args.network} on {args.memory}")
    print(f"{args.network} {args.memory}: {host['layers']} layers, {host['macs']:,} MACs, "
          f"{host['weight_bytes']:,} B of weights; host checks "
          + ("pass" if not host["failures"] else "FAIL: " + "; ".join(host["failures"])), flush=True)
    if host["failures"]:
        return 1
    failed = 0
    for runner in args.runner if args.gvsoc else ():
        text = simulate(out, runner, args.runs, args.timeout)
        (out / "gvsoc").mkdir(exist_ok=True)
        (out / "gvsoc" / f"{runner}.log").write_text(text)
        verdict = judge(parse(text), host["layers"], args.runs)
        (out / "gvsoc" / f"{runner}.json").write_text(json.dumps(verdict) + "\n")
        print(f"  gvsoc {runner}: {verdict['result']}, {verdict['detail']}, {verdict['median_us']} us", flush=True)
        failed += verdict["result"] != "pass"
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
